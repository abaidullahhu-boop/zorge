function mapsSearch(query) {
  return `https://www.google.com/maps/search/?api=1&query=${encodeURIComponent(query)}`
}

function place({
  id,
  title,
  tag,
  address,
  note,
  x,
  y,
  shape = 'icon',
  hitW,
  hitH,
  placement,
  mobile,
}) {
  return {
    id,
    title,
    tag,
    address,
    note,
    x,
    y,
    shape,
    hitW,
    hitH,
    placement,
    mobile,
    mapsUrl: mapsSearch(address),
  }
}

